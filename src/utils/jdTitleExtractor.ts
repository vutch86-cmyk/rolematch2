const PORTAL_NAMES = new Set([
  'linkedin',
  'itviec',
  'topcv',
  'vietnamworks',
  'careerviet',
  'glints',
  'careerbuilder',
  'jobsgo',
  '123job',
  'indeed',
  'glassdoor',
]);

function cleanInlineMarkdownAndQuotes(raw: string): string {
  return raw
    .replace(/^#+\s*/, '')
    .replace(/\*\*/g, '')
    .replace(/^[\s"'“”‘’•\-–—:*]+|[\s"'“”‘’•\-–—:*]+$/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function isGenericHeader(line: string): boolean {
  const normalized = cleanInlineMarkdownAndQuotes(line)
    .toLowerCase()
    .replace(/[:.!?]+$/, '')
    .trim();
  if (!normalized) return true;
  if (GENERIC_SECTION_HEADERS.has(normalized)) return true;
  if (/^(?:phần|section|part)\s*\d+/i.test(normalized)) return true;
  return false;
}

function cleanPortalSuffix(raw: string): string {
  return raw
    .replace(/\s*[|\-–—]\s*(?:LinkedIn|ITviec|TopCV|VietnamWorks|CareerViet|CareerBuilder|Glints|JobsGO|Indeed|Glassdoor).*$/i, '')
    .trim();
}

/**
 * Extracts structured { companyName, jobTitle } from JD text and optional file/URL source label.
 */
export function extractJobMetaFromJdText(
  jdText: string,
  sourceLabel?: string | null
): ExtractedJobMeta {
  let companyName = '';
  let jobTitle = '';

  const text = (jdText || '').replace(/\r\n/g, '\n').trim();
  const lines = text
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean);

  // 1. Check explicit labeled lines in JD text (top 40 lines)
  const labelLines = lines.slice(0, 40);
  for (const rawLine of labelLines) {
    const line = rawLine.replace(/\*\*/g, '').replace(/^[•\-*]\s*/, '').trim();

    // Match explicit Company Name labels
    if (!companyName) {
      const companyMatch = line.match(
        /^(?:công\s*ty(?:\s*\/\s*company)?|tên\s*công\s*ty|company(?:\s+name)?|tập\s*đoàn|ngân\s*hàng|đơn\s*vị(?:\s+tuyển\s+dụng)?|nhà\s*tuyển\s*dụng|hiring\s+organization|organization|employer|client)\s*[:\-–]\s*(.+)$/i
      );
      if (companyMatch && companyMatch[1]) {
        const candidate = cleanPortalSuffix(cleanInlineMarkdownAndQuotes(companyMatch[1]));
        if (candidate.length >= 2 && candidate.length <= 90 && !PORTAL_NAMES.has(candidate.toLowerCase())) {
          companyName = candidate;
        }
      }
    }

    // Match explicit Job Title labels
    if (!jobTitle) {
      const titleMatch = line.match(
        /^(?:\*\*)?(?:vị\s*trí(?:\s+tuyển\s+dụng|\s+ứng\s+tuyển|\s+công\s+việc)?|chức\s*danh(?:\s+công\s+việc)?|job\s*title|position(?:\s+title)?|role(?:\s+title)?|title)(?:\*\*)?\s*[:\-–]\s*(.+)$/i
      );
      if (titleMatch && titleMatch[1]) {
        const candidate = cleanPortalSuffix(cleanInlineMarkdownAndQuotes(titleMatch[1]));
        if (candidate.length >= 2 && candidate.length <= 110 && !isGenericHeader(candidate)) {
          jobTitle = candidate;
        }
      }
    }
  }

  // 2. Check Markdown H1/H2 heading at the top of JD (e.g., generated by URL extractor `# Job Title`)
  if (!jobTitle && lines.length > 0) {
    for (const line of lines.slice(0, 6)) {
      if (/^#{1,2}\s+/.test(line)) {
        const headingText = cleanPortalSuffix(cleanInlineMarkdownAndQuotes(line));
        if (
          headingText.length >= 3 &&
          headingText.length <= 110 &&
          !isGenericHeader(headingText) &&
          !PORTAL_NAMES.has(headingText.toLowerCase())
        ) {
          jobTitle = headingText;
          break;
        }
      }
    }
  }

  // 3. Check LinkedIn / Job Portal second-line subheader pattern: `Company Name · Location`
  if (!companyName && lines.length >= 2) {
    for (const line of lines.slice(0, 8)) {
      if (line.includes('·')) {
        const firstSegment = cleanInlineMarkdownAndQuotes(line.split('·')[0]);
        if (
          firstSegment.length >= 2 &&
          firstSegment.length <= 75 &&
          !isGenericHeader(firstSegment) &&
          !PORTAL_NAMES.has(firstSegment.toLowerCase()) &&
          !/^\d+\s*(?:ngày|giờ|tuần|tháng|days?|hours?|weeks?|months?|applicants?|ứng viên)/i.test(firstSegment)
        ) {
          companyName = firstSegment;
          break;
        }
      }
    }
  }

  // 4. Check prose patterns in JD text for Company Name & Job Title
  if (!companyName && text) {
    // e.g. "Công ty Cổ phần FPT Software tuyển dụng...", "Tại Ngân hàng TMCP Á Châu (ACB)..."
    const vnOrgMatch = text.match(
      /\b((?:Công\s+ty\s+(?:Cổ\s+phần|TNHH|Tài\s+chính|Bảo\s+hiểm|Chứng\s+khoán)|Tập\s+đoàn|Ngân\s+hàng\s+(?:TMCP|Thương\s+mại)?)\s+[A-ZÀÁẠẢÃÂẦẤẬẨẪĂẰẮẶẲẴÈÉẸẺẼÊỀẾỆỂỄÌÍỊỈĨÒÓỌỎÕÔỒỐỘỔỖƠỜỚỢỞỠÙÚỤỦŨƯỪỨỰỬỮỲÝỴỶỸĐ][\wÀ-ỹ\s&.,()-]{1,50}?)(?=\s+(?:tuyển\s+dụng|đang\s+tìm\s+kiếm|cần\s+tuyển|là\s+đơn\s+vị|tự\s+hào|cung\s+cấp|[,.\n]))/i
    );
    if (vnOrgMatch && vnOrgMatch[1]) {
      const candidate = cleanInlineMarkdownAndQuotes(vnOrgMatch[1]);
      if (candidate.length >= 4 && candidate.length <= 80) {
        companyName = candidate;
      }
    }
  }

  if (!jobTitle && text) {
    // e.g. "We are looking for a Senior Backend Engineer to join...", "tuyển dụng vị trí Trưởng phòng CNTT..."
    const roleProseMatch =
      text.match(
        /(?:tuyển\s+dụng\s+(?:vị\s+trí\s+)?| tìm\s+kiếm\s+(?:ứng\s+viên\s+cho\s+vị\s+trí\s+)?|ứng\s+tuyển\s+vị\s+trí\s+)([A-ZÀ-Ỹ][\wÀ-ỹ\s/&()+.-]{3,65}?)(?=\s+(?:tại|cho|làm\s+việc|có\s+kinh\s+nghiệm|để\s+tham\s+gia|[,.\n]))/i
      ) ||
      text.match(
        /(?:looking\s+for\s+(?:a|an)\s+(?:talented\s+|experienced\s+)?|seeking\s+(?:a|an)\s+(?:talented\s+|experienced\s+)?|hiring\s+(?:a|an)\s+|as\s+(?:a|an)\s+|role\s+of\s+)([A-Z][A-Za-z0-9\s/&()+.-]{3,65}?)(?=\s+(?:to\s+join|who\s+will|with\s+\d|at\s+[A-Z]|in\s+our|[,.\n]))/
      );
    if (roleProseMatch && roleProseMatch[1]) {
      const candidate = cleanInlineMarkdownAndQuotes(roleProseMatch[1]);
      if (candidate.length >= 3 && candidate.length <= 85 && !isGenericHeader(candidate)) {
        jobTitle = candidate;
      }
    }
  }

  // 5. Inspect sourceLabel (e.g. "LinkedIn: Senior React Dev - TechCorp" or "JD_FPT_AI_Engineer.pdf")
  if (sourceLabel && sourceLabel.trim()) {
    let rawSource = sourceLabel.trim();
    // Strip "File: " prefix if present
    rawSource = rawSource.replace(/^File:\s*/i, '').trim();

    // Check if sourceLabel is from URL Extractor: "PortalName: Title"
    const portalPrefixMatch = rawSource.match(
      /^(LinkedIn|ITviec|TopCV|VietnamWorks|CareerViet|CareerBuilder|Glints|JobsGO|Indeed|Glassdoor)\s*:\s*(.+)$/i
    );
    if (portalPrefixMatch) {
      const portalRest = cleanPortalSuffix(portalPrefixMatch[2].trim());
      if (portalRest && !/^https?:\/\//i.test(portalRest)) {
        // Check if portalRest contains "Title at Company" or "Title - Company"
        const atParts = portalRest.split(/\s+(?:at|tại|@)\s+/i);
        if (atParts.length === 2) {
          if (!jobTitle) jobTitle = cleanInlineMarkdownAndQuotes(atParts[0]);
          if (!companyName) companyName = cleanInlineMarkdownAndQuotes(atParts[1]);
        } else {
          const dashParts = portalRest.split(/\s+[-–—]\s+/);
          if (dashParts.length >= 2) {
            if (!jobTitle) jobTitle = cleanInlineMarkdownAndQuotes(dashParts[0]);
            if (!companyName) companyName = cleanInlineMarkdownAndQuotes(dashParts[1]);
          } else if (!jobTitle) {
            jobTitle = cleanInlineMarkdownAndQuotes(portalRest);
          }
        }
      }
    } else if (!/^https?:\/\//i.test(rawSource)) {
      // File name like "JD_Techcombank_IT_Manager.pdf"
      const withoutExt = rawSource
        .replace(/\.(pdf|docx|doc|txt|md|rtf|json)$/i, '')
        .replace(/^(?:jd|mo_ta_cong_viec|job_description)[\s_\-–]+/i, '')
        .replace(/[_]+/g, ' ')
        .trim();
      if (withoutExt.length >= 3 && withoutExt.length <= 90) {
        const dashParts = withoutExt.split(/\s*[-–—]\s*/).filter(Boolean);
        if (dashParts.length >= 2) {
          if (!companyName) companyName = dashParts[0].trim();
          if (!jobTitle) jobTitle = dashParts.slice(1).join(' - ').trim();
        } else if (!jobTitle) {
          jobTitle = withoutExt;
        }
      }
    }
  }

  // 6. Check if jobTitle itself contains "Role at Company" or "Company - Role"
  if (jobTitle && !companyName) {
    const atSplit = jobTitle.match(/^(.+?)\s+(?:at|tại|@)\s+([A-ZÀ-Ỹ][\wÀ-ỹ\s&.,()-]{1,50})$/i);
    if (atSplit) {
      jobTitle = cleanInlineMarkdownAndQuotes(atSplit[1]);
      companyName = cleanInlineMarkdownAndQuotes(atSplit[2]);
    }
  }

  // 7. Fallback to first non-generic heading/title line of JD if jobTitle is still empty
  if (!jobTitle && lines.length > 0) {
    for (const rawLine of lines.slice(0, 5)) {
      const isBulletLine = /^[•\-*+]\s+/.test(rawLine) || /^\d+[.)]\s+/.test(rawLine);
      const cleaned = cleanPortalSuffix(cleanInlineMarkdownAndQuotes(rawLine));
      if (
        !isBulletLine &&
        cleaned &&
        !isGenericHeader(cleaned) &&
        !PORTAL_NAMES.has(cleaned.toLowerCase()) &&
        !/^(?:công\s*ty|company|địa\s*điểm|location|mức\s*lương|salary|kinh\s*nghiệm|experience|hạn\s*nộp|deadline)\s*[:\-–]/i.test(cleaned) &&
        cleaned.length >= 3 &&
        cleaned.length <= 75 &&
        !cleaned.endsWith('.') &&
        !cleaned.endsWith(';')
      ) {
        jobTitle = cleaned;
        break;
      }
    }

    // If all top lines were bullets or long sentences, take a concise first line (<= 55 chars)
    if (!jobTitle) {
      for (const rawLine of lines.slice(0, 5)) {
        const cleaned = cleanPortalSuffix(cleanInlineMarkdownAndQuotes(rawLine));
        if (cleaned && !isGenericHeader(cleaned) && cleaned.length >= 3) {
          jobTitle = cleaned.length > 55 ? `${cleaned.slice(0, 52).trim()}...` : cleaned;
          break;
        }
      }
    }
  }

  return {
    companyName: companyName.trim(),
    jobTitle: jobTitle.trim(),
  };
}

/**
 * Strips legacy `- <username>` suffix and detects whether a title was generated by the old
 * `Vị trí ${jdKeywords[0].keyword} - ${username}` logic.
 */
export function stripLegacyUsernameSuffix(title: string, currentUsername?: string | null): string {
  let cleaned = (title || '').trim();
  if (!cleaned) return '';

  if (currentUsername) {
    const escaped = currentUsername.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    cleaned = cleaned.replace(new RegExp(`\\s*-\\s*${escaped}$`, 'i'), '').trim();
  }

  // Also strip common guest or single-token lowercase username suffix when preceded by "Vị trí "
  cleaned = cleaned.replace(/\s*-\s*(?:user_guest|[a-z0-9_]{3,20})$/i, (match) => {
    // Only strip if the token looks like a username (all lowercase/digits/underscore, no spaces)
    const token = match.replace(/^\s*-\s*/, '');
    if (/^[a-z0-9_]+$/.test(token)) {
      return '';
    }
    return match;
  }).trim();

  return cleaned;
}

/**
 * Checks if a HistoryItem title was auto-generated from the first JD skill keyword
 * (e.g. "Vị trí IT roadmap - vuta" or "Vị trí Quản lý chiến lược CNTT & Kiến trúc...").
 */
export function isLegacyKeywordHistoryTitle(
  title: string,
  jdKeywords?: Array<{ keyword: string }>
): boolean {
  const raw = (title || '').trim();
  if (!raw) return true;

  const withoutUser = stripLegacyUsernameSuffix(raw);
  if (!withoutUser) return true;

  const firstKeyword = jdKeywords?.[0]?.keyword?.trim();
  if (firstKeyword) {
    const expectedLegacy = `Vị trí ${firstKeyword}`.toLowerCase();
    if (withoutUser.toLowerCase() === expectedLegacy) {
      return true;
    }
  }

  // Also detect if title has trailing `- <lowercase_username>` and starts with `Vị trí `
  if (/^Vị\s+trí\s+.+\s+-\s+[a-z0-9_]+$/.test(raw)) {
    return true;
  }

  return false;
}

/**
 * Formats the display title for a Candidate History item using the canonical
 * "[Company Name] - [Job Title]" pattern (or "[Job Title]" when company name is unavailable).
 */
export function formatCandidateHistoryTitle(
  params: {
    companyName?: string | null;
    jobTitle?: string | null;
    fallbackTitle?: string | null;
    currentUsername?: string | null;
  },
  lang: 'vi' | 'en' = 'vi'
): string {
  const company = (params.companyName || '').trim();
  let role = stripLegacyUsernameSuffix(params.jobTitle || '', params.currentUsername);

  // Avoid duplicating "Company - Company - Role" if role already starts with company
  if (company && role && role.toLowerCase().startsWith(company.toLowerCase())) {
    const remainder = role.slice(company.length).replace(/^[\s\-–—:|@]+/, '').trim();
    if (remainder.length >= 2) {
      role = remainder;
    }
  }

  if (company && role) {
    return `${company} - ${role}`;
  }

  if (role) {
    return role;
  }

  if (company) {
    return `${company} - ${lang === 'en' ? 'Applied Position' : 'Vị trí ứng tuyển'}`;
  }

  const cleanedFallback = stripLegacyUsernameSuffix(params.fallbackTitle || '', params.currentUsername);
  if (cleanedFallback) {
    return cleanedFallback;
  }

  return lang === 'en' ? 'Applied Position' : 'Vị trí ứng tuyển';
}

/**
 * Automatically enriches and migrates an existing HistoryItem from localStorage
 * so legacy items (like "Vị trí IT roadmap - vuta") get structured companyName, jobTitle,
 * and a clean "[Company Name] - [Job Title]" title without losing user custom renames.
 */
export function enrichAndMigrateHistoryItem(
  item: HistoryItem,
  lang: 'vi' | 'en' = 'vi',
  currentUsername?: string | null
): HistoryItem {
  const extracted = extractJobMetaFromJdText(item.jdText || '', item.jdFileName || null);
  const keywords = item.analysis?.feature1?.jdKeywords || [];
  const isLegacy = isLegacyKeywordHistoryTitle(item.title, keywords);

  const companyName = (item.companyName || extracted.companyName || '').trim();
  let jobTitle = (item.jobTitle || extracted.jobTitle || '').trim();

  // If jobTitle is still empty or accidentally equals the first skill keyword when a better role wasn't found
  if (!jobTitle && !isLegacy && item.title) {
    jobTitle = stripLegacyUsernameSuffix(item.title, currentUsername);
  }

  // If user manually renamed the item (isCustomTitle: true), keep their custom title
  if (item.isCustomTitle && item.title?.trim()) {
    return {
      ...item,
      companyName: companyName || undefined,
      jobTitle: jobTitle || undefined,
    };
  }

  const formattedTitle = formatCandidateHistoryTitle(
    {
      companyName,
      jobTitle,
      fallbackTitle: isLegacy ? '' : item.title,
      currentUsername,
    },
    lang
  );

  return {
    ...item,
    title: formattedTitle,
    companyName: companyName || undefined,
    jobTitle: jobTitle || undefined,
  };
}
